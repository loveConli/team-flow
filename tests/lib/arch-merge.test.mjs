// tests/lib/arch-merge.test.mjs — arch-merge 重构回归测试（v0.35.0，v0.14 §62）
// Tier1 确定性 fixture：无 LLM，直接构造 change 产物断言确定性行为。
// 覆盖红队评审要求的负例：标题漂移 / 反引号表名 / marker 损坏 / 幂等 / 并发写锁 / 冲突 / 首轮 / dry-run。
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { run } from '../../scripts/lib/arch-merge.mjs';

function makeProject() {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'arch-merge-test-'));
  fs.mkdirSync(path.join(root, '.team-flow'), { recursive: true });
  fs.mkdirSync(path.join(root, 'docs', 'architecture'), { recursive: true });
  return root;
}

function makeChange(root, name, { aggregates, endpoints, ddl } = {}) {
  const dir = path.join(root, 'changes', name, 'architecture');
  fs.mkdirSync(path.join(dir, 'sql', 'ddl'), { recursive: true });
  const aggRows = (aggregates || ['| order:Order | order | Order | OrderItem | PlaceOrder | 总金额=明细和 | 订单事务 |']).join('\n');
  const epRows = (endpoints || ['| /api/orders | POST | order:Order | 下单 |']).join('\n');
  fs.writeFileSync(path.join(dir, 'architecture.md'),
`---
change_id: ${name}
date: 2026-08-05
arch_design_decision: required
---
## 2. To-Be 增量设计
| 聚合ID | 上下文 | 根实体 | 值对象 | 核心行为 | 关键不变量 | 事务边界 |
|--------|--------|--------|--------|---------|-----------|---------|
${aggRows}
## 5. 演进日志
| 日期 | 变更 ID | 内容 | 影响范围 |
|------|---------|------|---------|
| 2026-08-05 | ${name} | 测试变更 | 新建 |
`);
  fs.writeFileSync(path.join(dir, 'api.md'),
`---
change_id: ${name}
api_contract_manager: swagger
---
## 2.1 Command API
| 端点 | 方法 | 聚合 | 说明 |
|------|------|------|------|
${epRows}
`);
  fs.writeFileSync(path.join(dir, 'database.md'),
`# Database 增量设计

## 3. Schema 变更详情
| 脚本文件 | 操作类型 | 目标表 | 说明 |
|---------|---------|-------|------|
| sql/ddl/001.sql | CREATE TABLE | t_order | 订单表 |
`);
  if (ddl) fs.writeFileSync(path.join(dir, 'sql', 'ddl', '001.sql'), ddl);
  // v0.36.3：change 需带 state: closed 才能被 API-INDEX 扫描（isChangeClosed 过滤在途 change）
  fs.writeFileSync(path.join(root, 'changes', name, '.team-flow.yaml'), 'state: closed\n');
  return path.join(root, 'changes', name);
}

test('正常 merge：全局生成式产物完整', async () => {
  const root = makeProject();
  const change = makeChange(root, 'v1-C1');
  const result = await run({ _: [change], projectRoot: root });
  assert.equal(result.merged, true);
  const arch = fs.readFileSync(path.join(root, 'docs', 'architecture', 'ARCHITECTURE.md'), 'utf-8');
  assert.match(arch, /<!-- arch:current-state:begin -->/);
  assert.match(arch, /change:v1-C1/);
  assert.match(fs.readFileSync(path.join(root, 'docs', 'architecture', 'API-INDEX.md'), 'utf-8'), /\/api\/orders/);
  assert.match(fs.readFileSync(path.join(root, 'docs', 'architecture', 'DATABASE.md'), 'utf-8'), /generated by arch-merge/);
  fs.rmSync(root, { recursive: true, force: true });
});

test('幂等：同 change 双跑，演进日志标题唯一、DDL 块唯一', async () => {
  const root = makeProject();
  const change = makeChange(root, 'v1-C1', { ddl: 'CREATE TABLE t_order (id BIGINT);' });
  await run({ _: [change], projectRoot: root });
  await run({ _: [change], projectRoot: root });
  const arch = fs.readFileSync(path.join(root, 'docs', 'architecture', 'ARCHITECTURE.md'), 'utf-8');
  assert.equal((arch.match(/^### change:v1-C1$/gm) || []).length, 1);
  const schema = fs.readFileSync(path.join(root, 'docs', 'architecture', 'schema-baseline.sql'), 'utf-8');
  assert.equal((schema.match(/=== 001.sql/g) || []).length, 1);
  fs.rmSync(root, { recursive: true, force: true });
});

test('标题漂移容错：聚合表标题无序号点（## 2 To-Be）仍能提取', async () => {
  const root = makeProject();
  const change = makeChange(root, 'v1-C1');
  const archPath = path.join(change, 'architecture', 'architecture.md');
  fs.writeFileSync(archPath, fs.readFileSync(archPath, 'utf-8').replace('## 2. To-Be', '## 2 To-Be'));
  const result = await run({ _: [change], projectRoot: root });
  assert.equal(result.merged, true);
  assert.match(fs.readFileSync(path.join(root, 'docs', 'architecture', 'ARCHITECTURE.md'), 'utf-8'), /order:Order/);
  fs.rmSync(root, { recursive: true, force: true });
});

test('反引号表名容错：DDL 反引号表名被提取到物理模型', async () => {
  const root = makeProject();
  const change = makeChange(root, 'v1-C1', { ddl: 'CREATE TABLE `t_order` (id BIGINT);' });
  await run({ _: [change], projectRoot: root });
  assert.match(fs.readFileSync(path.join(root, 'docs', 'architecture', 'PHYSICAL-MODEL.md'), 'utf-8'), /t_order/);
  fs.rmSync(root, { recursive: true, force: true });
});

test('marker 损坏：双 end marker → abort 禁止写盘', async () => {
  const root = makeProject();
  const change = makeChange(root, 'v1-C1');
  await run({ _: [change], projectRoot: root });
  const p = path.join(root, 'docs', 'architecture', 'ARCHITECTURE.md');
  fs.writeFileSync(p, fs.readFileSync(p, 'utf-8') + '\n<!-- arch:current-state:end -->\n');
  let caught = '';
  try { await run({ _: [change], projectRoot: root }); } catch (e) { caught = e.message || String(e); }
  assert.ok(caught.includes('marker 不成对'), `expected marker abort, got: ${caught}`);
  fs.rmSync(root, { recursive: true, force: true });
});

test('写锁：.arch-merge.lock 存在 → abort（防并发 lost update）', async () => {
  const root = makeProject();
  const change = makeChange(root, 'v1-C1');
  fs.mkdirSync(path.join(root, '.arch-merge.lock'));
  let caught = '';
  try { await run({ _: [change], projectRoot: root }); } catch (e) { caught = e.message || String(e); }
  assert.ok(caught.includes('another arch-merge in progress'), `expected lock abort, got: ${caught}`);
  fs.rmSync(root, { recursive: true, force: true });
});

test('冲突：第二个 change 声明同聚合 → 阻断转产品级', async () => {
  const root = makeProject();
  const c1 = makeChange(root, 'v1-C1');
  const c2 = makeChange(root, 'v1-C2');
  await run({ _: [c1], projectRoot: root });
  const result = await run({ _: [c2], projectRoot: root });
  assert.equal(result.merged, false);
  assert.equal(result.reason, 'conflict');
  assert.match(result.conflicts[0], /order:Order/);
  fs.rmSync(root, { recursive: true, force: true });
});

test('dry-run：不落盘任何产物', async () => {
  const root = makeProject();
  const change = makeChange(root, 'v1-C1');
  await run({ _: [change], projectRoot: root, dryRun: true });
  assert.equal(fs.existsSync(path.join(root, 'docs', 'architecture', 'ARCHITECTURE.md')), false);
  assert.equal(fs.existsSync(path.join(root, '.arch-merge.lock')), false);
  fs.rmSync(root, { recursive: true, force: true });
});

test('首轮无 schema-baseline：生成式产物正常降级（无 DDL 不崩）', async () => {
  const root = makeProject();
  const change = makeChange(root, 'v1-C1'); // 无 ddl
  await run({ _: [change], projectRoot: root });
  const pm = fs.readFileSync(path.join(root, 'docs', 'architecture', 'PHYSICAL-MODEL.md'), 'utf-8');
  assert.match(pm, /generated by arch-merge/);
  fs.rmSync(root, { recursive: true, force: true });
});
